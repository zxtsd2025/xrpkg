#!/usr/bin/env bash
# 生成目标 Rootfs 的 /etc/fstab。
#
# 用法（必须 root）:
#   scripts/gen-fstab.sh [/mnt/lfs] [/dev/nvme0n1p3] [/dev/nvme0n1p1] [/dev/nvme0n1p2]
#
# UUID 全部来自 `blkid -s UUID -o value`，不依赖 lsblk 的展示格式。
# swap 只写进 fstab，绝不在这里执行 swapon。
set -euo pipefail

ROOT="${1:-/mnt/lfs}"
ROOT_DEV="${2:-/dev/nvme0n1p3}"
ESP_DEV="${3:-/dev/nvme0n1p1}"
SWAP_DEV="${4:-/dev/nvme0n1p2}"

die() {
    echo "错误: $*" >&2
    exit 1
}

[[ ${EUID} -eq 0 ]] || die "需要 root 权限才能写入 $ROOT/etc/fstab"
[[ -d "$ROOT" ]] || die "目标 Rootfs 不存在: $ROOT"
command -v blkid >/dev/null 2>&1 || die "找不到 blkid（util-linux）"

for device in "$ROOT_DEV" "$ESP_DEV" "$SWAP_DEV"; do
    [[ -b "$device" ]] || die "不是块设备: $device"
done

uuid_of() {
    local device="$1" uuid
    uuid="$(blkid -s UUID -o value "$device" 2>/dev/null || true)"
    # 某些环境下内核对已挂载设备的 blkid 缓存为空，回退到 udev/lsblk 的同一份
    # UUID 数据；两者都来自分区超级块，不会伪造值。
    if [[ -z "$uuid" ]] && command -v lsblk >/dev/null 2>&1; then
        uuid="$(lsblk -no UUID "$device" 2>/dev/null | head -n 1 | tr -d '[:space:]')"
    fi
    [[ -n "$uuid" ]] || die "无法从 $device 读取 UUID（分区未格式化或设备不存在？）"
    printf '%s\n' "$uuid"
}

ROOT_UUID="$(uuid_of "$ROOT_DEV")"
ROOT_PARTUUID="$(blkid -s PARTUUID -o value "$ROOT_DEV" 2>/dev/null || true)"
if [[ -z "$ROOT_PARTUUID" ]] && command -v lsblk >/dev/null 2>&1; then
    ROOT_PARTUUID="$(lsblk -no PARTUUID "$ROOT_DEV" 2>/dev/null | head -n 1 | tr -d '[:space:]')"
fi
[[ -n "$ROOT_PARTUUID" ]] || die "无法从 $ROOT_DEV 读取 PARTUUID"
ESP_UUID="$(uuid_of "$ESP_DEV")"
SWAP_UUID="$(uuid_of "$SWAP_DEV")"

echo "==> 根分区   $ROOT_DEV  UUID=$ROOT_UUID  PARTUUID=$ROOT_PARTUUID"
echo "==> EFI 分区 $ESP_DEV   UUID=$ESP_UUID"
echo "==> swap     $SWAP_DEV  UUID=$SWAP_UUID"

install -d -m 0755 "$ROOT/etc"
TMP_FILE="$(mktemp "$ROOT/etc/.fstab.XXXXXX")"
trap 'rm -f "$TMP_FILE"' EXIT

cat >"$TMP_FILE" <<EOF
# /etc/fstab: static file system information.
# Generated by xrpkg scripts/gen-fstab.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ').
#
# <file system>                             <mount point>  <type>  <options>     <dump>  <pass>
PARTUUID=$ROOT_PARTUUID  /       ext4    defaults       0       1
UUID=$ESP_UUID   /boot/efi      vfat    umask=0077     0       2
UUID=$SWAP_UUID  none           swap    defaults       0       0
EOF

chmod 0644 "$TMP_FILE"
install -m 0644 "$TMP_FILE" "$ROOT/etc/fstab"
echo "==> 已写入 $ROOT/etc/fstab"
cat "$ROOT/etc/fstab"
